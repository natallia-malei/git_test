// Тернарный оператор
// Конспект по статье https://doka.guide/js/ternary-operator/

// =============================================
// 1. Что это и синтаксис
// =============================================
// Тернарный - значит "из трех частей". У оператора три операнда:
//   условие ? значение_если_true : значение_если_false
//
// Это ВЫРАЖЕНИЕ - то есть оно возвращает значение,
// которое можно присвоить, передать в функцию или вернуть.
// Подробнее про это смотри в Основы/expressions-vs-statements.ts

const num = 5;
const message = num === 5 ? "Пять" : "Не пять";
console.log(message); // "Пять"

// =============================================
// 2. Сравнение с if/else
// =============================================
// Тернарка - компактная замена if/else, когда нужно ВЫБРАТЬ значение.

// Через if/else (4 строки + объявление let):
const n = 10;
let resultIf: string;
if (n > 10) {
  resultIf = "больше 10";
} else {
  resultIf = "меньше или равно 10";
}
console.log(resultIf);

// Через тернарку (одна строка + const):
const resultTernary = n > 10 ? "больше 10" : "меньше или равно 10";
console.log(resultTernary);

// Плюсы тернарки:
// - короче
// - сразу const (а не let с дозаписью)
// - сразу видно, что это выбор значения, а не действие

// =============================================
// 3. Возврат из функции
// =============================================
// Удобно в стрелочных функциях без фигурных скобок.

const isAdult = (age: number): string => (age >= 18 ? "взрослый" : "ребенок");

console.log(isAdult(20)); // "взрослый"
console.log(isAdult(10)); // "ребенок"

// То же через if/else выглядит громоздко:
const isAdultIf = (age: number): string => {
  if (age >= 18) {
    return "взрослый";
  } else {
    return "ребенок";
  }
};
console.log(isAdultIf(20));

// =============================================
// 4. Вложенные тернарки (осторожно!)
// =============================================
// Можно вкладывать одну тернарку в другую,
// но читаемость быстро падает.

const score = 75;
const grade =
  score >= 90
    ? "A"
    : score >= 80
      ? "B"
      : score >= 70
        ? "C"
        : score >= 60
          ? "D"
          : "F";
console.log(grade); // "C"

// Эта запись понятна благодаря выравниванию по столбцам.
// Без выравнивания вложенные тернарки превращаются в кашу:
const ugly = score >= 90 ? "A" : score >= 80 ? "B" : score >= 70 ? "C" : "F";
console.log(ugly);

// Правило: если вложенность больше 2 уровней - лучше switch или if/else if.

// =============================================
// 5. TS-специфика: сужение типов
// =============================================
// TypeScript понимает тернарку и УЖЕ внутри веток знает уточненный тип.

const formatValue = (v: string | number): string => {
  return typeof v === "string"
    ? v.toUpperCase() // здесь v точно string
    : v.toFixed(2); // здесь v точно number
};

console.log(formatValue("hi")); // "HI"
console.log(formatValue(3.1415)); // "3.14"

// То же самое в if/else работало бы аналогично, но тернарка делает
// связку "проверка -> результат" более явной.

// =============================================
// 6. TS-специфика: вывод объединения типов
// =============================================
// Если ветки возвращают разные типы - TS выведет их объединение.

const pick = (flag: boolean) => (flag ? "да" : 42);
// тип pick: (flag: boolean) => string | number

const v1 = pick(true); // string | number
const v2 = pick(false); // string | number
console.log(v1, v2);

// =============================================
// 7. Тернарка vs || (логическое ИЛИ)
// =============================================
// Частая путаница. Они делают РАЗНЫЕ вещи.

// Тернарка проверяет ЯВНОЕ условие:
const name1 = "";
const display1 = name1.length > 0 ? name1 : "Гость";
console.log(display1); // "Гость"

// || возвращает левый операнd, если он "правдивый", иначе правый.
// "Правдивый" - это все, кроме: false, 0, "", null, undefined, NaN.
const name2 = "";
const display2 = name2 || "Гость"; // "" - "ложно", поэтому "Гость"
console.log(display2); // "Гость"

// Но || ловит ВСЕ ложные значения, включая 0 - это часто баг:
const count = 0;
const display3 = count || "нет данных"; // получим "нет данных", а хотели "0"
console.log(display3);

// Решение: либо явная тернарка, либо ?? (nullish coalescing).

// =============================================
// 8. Тернарка vs ?? (nullish coalescing)
// =============================================
// ?? возвращает правую часть только если левая null или undefined.
// 0, "", false НЕ считаются "пустыми".

const count2 = 0;
const display4 = count2 ?? "нет данных"; // 0 не nullish, получим 0
console.log(display4); // 0

// Тернарный аналог для понимания:
const display5 =
  count2 === null || count2 === undefined ? "нет данных" : count2;
console.log(display5); // 0

// =============================================
// 9. Тернарка для побочного эффекта - плохо
// =============================================
// Тернарка СОЗДАНА для ВЫБОРА ЗНАЧЕНИЯ, а не для действий.
// Использовать ее ради побочного эффекта - плохой стиль.

const isLoggedIn = true;

// Плохо - тернарка ради вызовов функций:
isLoggedIn ? console.log("привет") : console.log("войдите");

// Хорошо - if/else, потому что это действие, а не выбор значения:
if (isLoggedIn) {
  console.log("привет");
} else {
  console.log("войдите");
}

// Хорошо - тернарка для выбора значения, которое уже логируется:
console.log(isLoggedIn ? "привет" : "войдите");

// =============================================
// 10. Тернарка в шаблонных строках
// =============================================
// Тернарка - выражение, поэтому ее можно вставлять в ${...}.

const items = 3;
const text = `У вас ${items} ${items === 1 ? "товар" : "товаров"}`;
console.log(text); // "У вас 3 товаров"

// =============================================
// 11. Маленькая проверка

const evenOrOdd = (n: number): string => (n % 2 === 0 ? "Even" : "Odd");

console.log(evenOrOdd(2)); // ожидается: "Even"
console.log(evenOrOdd(0)); // ожидается: "Even"
console.log(evenOrOdd(7)); // ожидается: "Odd"
console.log(evenOrOdd(-1)); // ожидается: "Odd"

// =============================================
// Задачка в стиле Codewars (8 kyu): Quarter of the Year
// =============================================
// Создай функцию quarterOf, которая принимает номер месяца (число от 1 до 12)
// и возвращает номер квартала года, к которому относится этот месяц:
//
//   месяцы 1, 2, 3    -> квартал 1
//   месяцы 4, 5, 6    -> квартал 2
//   месяцы 7, 8, 9    -> квартал 3
//   месяцы 10, 11, 12 -> квартал 4
//
// Используй ВЛОЖЕННЫЕ тернарные операторы (см. раздел 4 этого файла).
//
// Примеры:
//   quarterOf(2)  -> 1
//   quarterOf(5)  -> 2
//   quarterOf(8)  -> 3
//   quarterOf(11) -> 4
//
// Подсказка: тебе нужно проверить, в какой из четырех диапазонов попадает month.
// Самый удобный способ - проверять "month <= 3", "month <= 6", "month <= 9",
// а последний кейс будет "иначе - 4-й квартал".
//
// Решение пиши здесь:

const quarterOf = (month: number): number => {
  if (month < 4) return 1;
  if (month < 7) return 2;
  if (month < 10) return 3;
  return 4;
};

console.log(quarterOf(2)); // ожидается: 1
console.log(quarterOf(5)); // ожидается: 2
console.log(quarterOf(8)); // ожидается: 3
console.log(quarterOf(11)); // ожидается: 4


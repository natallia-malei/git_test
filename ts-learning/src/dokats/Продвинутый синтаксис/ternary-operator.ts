//   "Even" - если число четное
//   "Odd"  - если число нечетное
//
// Используй ТЕРНАРНЫЙ оператор, а не if/else.
//
// Примеры:
//   evenOrOdd(2)   -> "Even"
//   evenOrOdd(0)   -> "Even"
//   evenOrOdd(7)   -> "Odd"

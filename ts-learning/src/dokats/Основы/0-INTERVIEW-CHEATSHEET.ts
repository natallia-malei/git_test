//   - type для всего по умолчанию
//   - interface когда нужно extends/implements или declaration merging

// Объединения - ТОЛЬКО через type:
type Result = "success" | "error" | "loading";

// Пересечения:
type Named = { name: string };
type Aged = { age: number };
type Person = Named & Aged; // обе формы вместе

const me: Person = { name: "Аня", age: 25 };

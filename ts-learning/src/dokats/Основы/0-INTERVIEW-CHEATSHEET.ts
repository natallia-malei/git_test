// Q: Чем отличаются var, let, const?
// A: var - функциональная область, поднимается с undefined,
//    let/const - блочная, TDZ, const запрещает переприсваивание.

// Q: Что такое замыкание?
// A: Функция, которая помнит переменные внешней области, в которой
//    она была создана, после ее завершения. Пример: счетчик через
//    makeCounter().

// Q: == или ===?
// A: Всегда ===. == делает coercion и дает странные результаты.

// Q: null vs undefined?
// A: undefined - переменная не инициализирована или значение не передано.
//    null - явное "ничего", присвоенное программистом.

// Q: Что такое this?
// A: Контекст вызова функции. Зависит от того, КАК вызвана:
//      obj.fn() - this = obj
//      fn()     - this = undefined (strict) или globalThis
//      arrow    - this берет из лексической области (родителя)
//    Стрелочные функции НЕ имеют своего this.

// Q: type vs interface?
// A: На практике почти то же. type универсальнее (union, литералы),
//    interface поддерживает declaration merging и привычен для классов.

// Q: any vs unknown?
// A: any выключает проверку типов (опасно). unknown безопасно -
//    обязывает проверить тип перед использованием.

// Q: Что такое generic?
// A: "Параметр типа" - дает универсальность без потери типизации.
//    Пример: const first = <T>(arr: T[]): T => arr[0];

// Q: Что выведет?
//    console.log(typeof null);
// A: "object" (исторический баг JS, ломать не стали).

// Q: Что такое NaN?
// A: "Not a Number", тип number. NaN !== NaN.
//    Проверка: Number.isNaN(x).

// Q: Все falsy значения?
// A: false, 0, -0, 0n, "", null, undefined, NaN. И больше ничего.

// Q: Что такое iterable и итератор?
// A: Iterable - объект со [Symbol.iterator]() методом.
//    Итератор - объект с next() -> { value, done }.
//    Все встроенные коллекции iterable.

// Q: Чем отличается for...in от for...of?
// A: in перебирает КЛЮЧИ (для объектов), of - ЗНАЧЕНИЯ (для итерируемых).
//    in не использовать для массивов.


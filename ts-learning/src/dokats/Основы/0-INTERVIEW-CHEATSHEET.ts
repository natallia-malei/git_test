// =================================================================
// 7. == vs ===  (СТРОГОЕ РАВЕНСТВО)
// =================================================================
// === - сравнивает БЕЗ приведения типов. Используй всегда его.
// ==  - сравнивает С приведением. Дает странные результаты.

console.log(0 == "0");        // true  (приведение)
console.log(0 === "0");       // false (типы разные)
console.log(null == undefined); // true  (специальное правило)
console.log(null === undefined); // false
console.log(NaN === NaN);     // false! всегда. Проверяй через Number.isNaN

// =================================================================
// 8. TRUTHY / FALSY
// =================================================================
// FALSY (8 значений): false, 0, -0, 0n, "", null, undefined, NaN
// Все остальное - truthy: "0", "false", [], {}, любые объекты и т.д.

if ([]) console.log("[] truthy");           // выполнится
if ({}) console.log("{} truthy");           // выполнится
if ("0") console.log("'0' truthy");         // выполнится! строка не пустая
if (0) console.log("не выполнится");

// Опасный момент: || ловит ВСЕ falsy, ?? только null/undefined.
const port = 0;
const realPort = port || 8080;   // 8080 - неправильно, 0 валидный порт!
const safePort = port ?? 8080;   // 0    - правильно
console.log(realPort, safePort);


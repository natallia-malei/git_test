// 15. СУЖЕНИЕ ТИПОВ (TYPE NARROWING)
// =================================================================
// TS умнее, чем кажется. После проверки тип сужается.

const printValue = (v: string | number | null): void => {
  if (v === null) {
    return; // v: null
  }
  if (typeof v === "string") {
    console.log(v.toUpperCase()); // v: string
    return;
  }
  console.log(v.toFixed(2));      // v: number (остается только это)
};

printValue("hi");
printValue(3.14);
printValue(null);


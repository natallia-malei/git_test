// 13. any vs unknown vs never (КЛАССИКА СОБЕСА)
// =================================================================
// any     - "выключает" типы. Можно ВСЕ. Использовать ТОЛЬКО в крайнем случае.
// unknown - "что-то есть, не знаю что". Безопасный any.
//           Перед использованием НУЖНА проверка типа.
// never   - "это никогда не случится" (упавшая функция, недостижимая ветка).

const x: any = "abc";
x.toFixed();         // OK (но в рантайме упадет!)
x();                 // OK (но упадет!)

const y: unknown = "abc";
// y.toFixed();      // Ошибка - сначала проверь тип
if (typeof y === "string") {
  y.toUpperCase();   // OK после сужения
}

const throwErr = (msg: string): never => { throw new Error(msg); };
console.log(x, y, throwErr);


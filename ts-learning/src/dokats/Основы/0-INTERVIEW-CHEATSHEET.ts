// 14. ОПЦИОНАЛЬНОСТЬ И NULL-БЕЗОПАСНОСТЬ
// =================================================================

type Profile = {
  name: string;
  age?: number;          // опциональное поле (может отсутствовать)
  email: string | null;  // может быть null
};

const profile: Profile = { name: "Аня", email: null };

// Опциональная цепочка ?. - читать вложенное без ошибки:
const len = profile.email?.length; // undefined, не ошибка
console.log(len);

// Nullish coalescing ?? - значение по умолчанию для null/undefined:
const safeAge = profile.age ?? 0;
console.log(safeAge);

// Type assertion as - "поверь мне":
const someValue: unknown = "abc";
const strLen = (someValue as string).length;
console.log(strLen);


// Хранение по ссылке и по значению
// Конспект по статье https://doka.guide/js/ref-type-vs-value-type/

// =============================================
// 1. Две группы типов
// =============================================
// ПРИМИТИВЫ хранятся "по значению":
//   number, string, boolean, null, undefined, symbol, bigint
// ССЫЛОЧНЫЕ типы хранятся "по ссылке":
//   object, array, function (все, что не примитив)

// Аналогия: примитив - это ложка в ящике.
// Ссылка - это записка в ящике с адресом, где лежит ложка.

// =============================================
// 2. Копирование примитивов
// =============================================
// При присваивании примитива создается НЕЗАВИСИМАЯ копия значения.

let a = 5;
let b = a;   // в b скопировалось само число 5
b = 10;
console.log(a); // 5  - a не изменился
console.log(b); // 10

// =============================================
// 3. Копирование объектов
// =============================================
// При присваивании объекта копируется только АДРЕС.
// Обе переменные указывают на один и тот же объект в памяти.

const cat = { name: "Барсик" };
const cat2 = cat;       // cat2 указывает на тот же объект
cat2.name = "Мурзик";
console.log(cat.name);  // "Мурзик"  - изменился через cat2!
console.log(cat2.name); // "Мурзик"

// Это работает даже с const. const запрещает менять САМУ ссылку,
// но не запрещает менять объект, на который ссылка указывает.

// =============================================
// 4. Сравнение через ===
// =============================================
// Для примитивов сравниваются значения.
// Для объектов сравниваются ССЫЛКИ, а не содержимое.

const p1 = 100;
const p2 = 100;
console.log(p1 === p2); // true  - значения равны

const obj1 = { x: 1 };
const obj2 = { x: 1 };
console.log(obj1 === obj2); // false! разные объекты в памяти

const obj3 = obj1;
console.log(obj1 === obj3); // true  - одна и та же ссылка

// =============================================
// 5. Передача в функцию
// =============================================
// Примитив передается копией - оригинал не меняется.
// Объект передается по ссылке - функция может мутировать оригинал.

const increment = (n: number): void => {
  n = n + 1;
  console.log("внутри:", n);
};

let num = 5;
increment(num);
console.log("снаружи:", num); // 5  - не изменился

const addItem = (arr: number[]): void => {
  arr.push(999);
};

const list = [1, 2, 3];
addItem(list);
console.log(list); // [1, 2, 3, 999]  - изменился!

// =============================================
// 6. Поверхностное копирование объекта
// =============================================
// Чтобы получить НЕЗАВИСИМУЮ копию объекта - используется спред {...obj}
// или Object.assign({}, obj).

const original = { name: "Барсик", age: 3 };
const copy = { ...original };  // новый объект с теми же полями
copy.name = "Мурзик";
console.log(original.name); // "Барсик"  - не задет
console.log(copy.name);     // "Мурзик"

// Для массивов аналогично:
const arr1 = [1, 2, 3];
const arr2 = [...arr1];
arr2.push(4);
console.log(arr1); // [1, 2, 3]
console.log(arr2); // [1, 2, 3, 4]

// =============================================
// 7. Подвох поверхностного копирования
// =============================================
// Спред копирует только ВЕРХНИЙ уровень.
// Вложенные объекты остаются общими ссылками.

const userA = {
  name: "Аня",
  address: { city: "Минск" }
};

const userB = { ...userA };       // верхний уровень скопировался
userB.name = "Боря";              // меняем только userB - ок
userB.address.city = "Москва";    // меняем ВЛОЖЕННЫЙ объект!

console.log(userA.name);         // "Аня"     - не задет
console.log(userA.address.city); // "Москва"  - задет! address общий

// Для "глубокой" копии нужно либо рекурсивно копировать,
// либо использовать structuredClone (современный способ):
const userC = structuredClone(userA);
userC.address.city = "Берлин";
console.log(userA.address.city); // "Москва" - теперь userA защищен

// =============================================
// 8. TS-специфика: readonly
// =============================================
// TypeScript умеет защищать от мутаций НА УРОВНЕ ТИПОВ.

type Point = {
  readonly x: number;
  readonly y: number;
};

const point: Point = { x: 1, y: 2 };
// point.x = 10;  // Ошибка компиляции: Cannot assign to 'x' because it is readonly

// Утилитарный тип Readonly<T> делает все поля readonly:
type ReadonlyCat = Readonly<{ name: string; age: number }>;
const fixedCat: ReadonlyCat = { name: "Барсик", age: 3 };
// fixedCat.name = "Мурзик";  // Ошибка компиляции

// ВАЖНО: readonly работает только в TS, на этапе компиляции.
// В рантайме объект остается обычным и его можно мутировать через any.

// =============================================
// 9. ReadonlyArray и as const
// =============================================
// Для массивов есть ReadonlyArray<T> или сокращение readonly T[].

const nums: readonly number[] = [1, 2, 3];
// nums.push(4);  // Ошибка: метода push нет у readonly массива

// as const "замораживает" литерал на уровне типов:
const colors = ["red", "green", "blue"] as const;
// тип будет readonly ["red", "green", "blue"]
// colors.push("yellow"); // Ошибка

// =============================================
// 10. Структурная типизация != идентичность
// =============================================
// TS считает типы СОВМЕСТИМЫМИ по структуре, но это касается ТИПОВ.
// В рантайме два объекта с одинаковыми полями - все равно разные ссылки.

type Cat = { name: string };
const c1: Cat = { name: "Барсик" };
const c2: Cat = { name: "Барсик" };

console.log(c1 === c2); // false  - разные объекты!
// TS не путает совместимость типов с равенством значений.

// =============================================
// 11. Каверзный пример (часто на собеседованиях)
// =============================================
const fox = { isHunter: true };
let mouse: { isHunter: boolean | undefined } = { isHunter: false };
mouse = fox as typeof mouse;     // теперь mouse и fox - одна ссылка
fox.isHunter = false;
mouse.isHunter = undefined;       // меняем общий объект
console.log(fox.isHunter);        // undefined  - изменился!

// =============================================
// Итог
// =============================================
// - Примитивы копируются по значению, объекты - по ссылке
// - === для объектов сравнивает ссылки, не содержимое
// - Спред {...obj} делает поверхностную копию
// - structuredClone делает глубокую копию
// - readonly в TS защищает от мутаций на этапе компиляции
// - Главное правило: если функция принимает объект - помни,
//   что она может его изменить. Если не должна - помечай readonly.

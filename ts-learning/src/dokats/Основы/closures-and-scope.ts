// Области видимости и замыкания в TypeScript
// Конспект по статье https://doka.guide/js/closures/

// =============================================
// 1. Область видимости - что это
// =============================================
// Область видимости (scope) - это часть программы, где переменная
// существует и к ней можно обратиться.
// Аналогия: коробки, вложенные друг в друга.
// Изнутри коробки видно наружу, снаружи внутрь - нет.

// В TS есть 4 типа областей видимости:
//   1. Глобальная (global)
//   2. Модульная (module)
//   3. Функциональная (function)
//   4. Блочная (block)

// =============================================
// 2. Модульная область видимости (TS-важно!)
// =============================================
// В TypeScript ЛЮБОЙ файл, содержащий хотя бы один import/export,
// автоматически становится МОДУЛЕМ.
// Переменные верхнего уровня модуля доступны только в этом файле.

// Этот файл сейчас НЕ модуль (нет import/export),
// поэтому такие переменные технически "глобальные" для проекта.
// Чтобы сделать файл модулем - достаточно добавить "export {}" в конце.

const moduleLevel = "видна везде в этом файле";
console.log(moduleLevel);

// =============================================
// 3. Функциональная область видимости
// =============================================
// Переменные, объявленные внутри функции, доступны только внутри нее.

function outer(): void {
  const inside = "только для outer";
  console.log(inside);
}
outer();
// console.log(inside);  // Ошибка: Cannot find name 'inside'

// =============================================
// 4. Блочная область видимости (let/const vs var)
// =============================================
// let и const ограничены БЛОКОМ - любыми {} (if, for, просто {}).
// var игнорирует блоки и видна на уровне всей функции.

if (true) {
  const blockOnly = "только внутри if";
  let alsoBlockOnly = 42;
  console.log(blockOnly, alsoBlockOnly);
}
// console.log(blockOnly);  // Ошибка

// Можно использовать одно и то же имя в разных блоках:
{
  const name = "первый блок";
  console.log(name);
}
{
  const name = "второй блок"; // не конфликтует
  console.log(name);
}

// =============================================
// 5. Лексическая область видимости
// =============================================
// "Лексическая" значит: вложенная функция видит переменные
// того МЕСТА, где она была НАПИСАНА (а не где вызвана).
// Это фундамент замыканий.

function greetMaker(): () => void {
  const greeting = "Привет!";
  function greet(): void {
    console.log(greeting); // видит greeting из родителя
  }
  return greet;
}

const sayHi = greetMaker();
sayHi(); // "Привет!"  - greeting остался доступен!

// =============================================
// 6. Замыкание (closure)
// =============================================
// Замыкание возникает, когда внутренняя функция ИСПОЛЬЗУЕТ переменные
// внешней функции. Внешняя функция уже завершилась, но эти переменные
// "выжили", потому что внутренняя функция их захватила.

function makeCounter(): () => number {
  let count = 0; // эта переменная будет захвачена
  return (): number => {
    count = count + 1;
    return count;
  };
}

const counter = makeCounter();
console.log(counter()); // 1
console.log(counter()); // 2
console.log(counter()); // 3  - count живет между вызовами!

// Каждый вызов makeCounter создает СВОЕ замыкание со своим count:
const counterA = makeCounter();
const counterB = makeCounter();
console.log(counterA()); // 1
console.log(counterA()); // 2
console.log(counterB()); // 1  - независимый счетчик

// =============================================
// 7. Классический баг с var в цикле
// =============================================
// var игнорирует блок цикла, поэтому все колбэки видят ОДНУ переменную i.
// Когда они срабатывают, цикл уже закончился и i = 3.

console.log("--- var ---");
for (var i = 0; i < 3; i++) {
  setTimeout(() => console.log("var i =", i), 0);
}
// Выведет: 3, 3, 3  - все колбэки видят одну i, которая уже = 3

// С let каждая итерация создает СВОЮ переменную в своем блоке.
console.log("--- let ---");
for (let j = 0; j < 3; j++) {
  setTimeout(() => console.log("let j =", j), 0);
}
// Выведет: 0, 1, 2  - каждый колбэк замкнул свою j

// =============================================
// 8. Хойстинг (hoisting)
// =============================================
// var "поднимается" наверх своей функции и инициализируется undefined.
// let и const тоже поднимаются, но обращение к ним до объявления
// дает ошибку - это называется Temporal Dead Zone (TDZ).

function hoistDemo(): void {
  console.log(varOne); // undefined  - var есть, но без значения
  // console.log(letOne); // ReferenceError: TDZ
  var varOne = 10;
  let letOne = 20;
  console.log(varOne, letOne);
}
hoistDemo();

// Объявления функций тоже поднимаются - вместе с телом:
sayHello(); // работает!
function sayHello(): void {
  console.log("hello");
}

// А вот стрелочные функции, присвоенные через const, НЕ поднимаются:
// sayBye();   // ReferenceError
const sayBye = (): void => console.log("bye");
sayBye();

// =============================================
// 9. Замыкания и приватность
// =============================================
// Через замыкание можно создавать "приватные" переменные,
// доступ к которым только через возвращенные функции.

function makeWallet(initial: number) {
  let balance = initial; // приватная переменная

  return {
    deposit: (amount: number): void => {
      balance += amount;
    },
    withdraw: (amount: number): boolean => {
      if (amount > balance) return false;
      balance -= amount;
      return true;
    },
    getBalance: (): number => balance,
  };
}

const wallet = makeWallet(100);
wallet.deposit(50);
console.log(wallet.getBalance()); // 150
wallet.withdraw(30);
console.log(wallet.getBalance()); // 120
// wallet.balance       // Ошибка: balance недоступен напрямую

// =============================================
// 10. TS-специфика: области видимости ТИПОВ
// =============================================
// В TypeScript типы тоже имеют область видимости.
// type и interface, объявленные внутри функции - локальны.

function processUser(): void {
  type LocalUser = { name: string; age: number }; // тип виден только здесь
  const u: LocalUser = { name: "Аня", age: 25 };
  console.log(u);
}
// const x: LocalUser = ... // Ошибка: тип LocalUser не виден снаружи

// На уровне модуля тип виден везде в файле:
type ModuleUser = { id: number };
const user1: ModuleUser = { id: 1 };
console.log(user1);

// =============================================
// 11. TS-специфика: сужение типов в замыканиях
// =============================================
// TS обычно сужает тип после проверки.
// Но в замыкании, которое вызывается ПОЗЖЕ, сужение НЕ сохраняется -
// потому что между проверкой и вызовом значение могло измениться.

function trickyClosure(value: string | null): () => void {
  if (value === null) return () => console.log("ничего");

  // здесь value сужен до string
  console.log(value.toUpperCase()); // OK

  return () => {
    // а здесь TS снова считает value как string | null
    // потому что между объявлением и вызовом могло что-то произойти
    // console.log(value.toUpperCase()); // Ошибка: value possibly null
    console.log(value); // OK
  };
}
trickyClosure("hi")();

// Решение - сохранить сужение в const:
function safeClosure(value: string | null): () => void {
  if (value === null) return () => console.log("ничего");
  const safe = value; // тип const safe: string
  return () => console.log(safe.toUpperCase()); // OK
}
safeClosure("hi")();

// =============================================
// 12. IIFE (Immediately Invoked Function Expression)
// =============================================
// Это функция, которая вызывается сразу при объявлении.
// Раньше использовали для изоляции переменных в эпоху одного <script>.
// В TS почти не нужно - модули решают ту же задачу.

(function (): void {
  const isolated = "никто извне меня не видит";
  console.log(isolated);
})();

// Современная альтернатива - блок:
{
  const alsoIsolated = "то же самое, проще";
  console.log(alsoIsolated);
}


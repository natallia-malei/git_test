// Порядок выполнения в JavaScript/TypeScript
// Конспект по статье https://doka.guide/js/execution-order/

// =============================================
// 1. Последовательное выполнение
// =============================================
// Код читается сверху вниз, строка за строкой.

console.log("Привет");
console.log("Я - вторая строка");

// В TS то же самое - типы не меняют порядок выполнения,
// они проверяются на этапе компиляции, а не во время работы кода.

const greeting: string = "Привет";
const secondLine: string = "Я - вторая строка";

console.log(greeting);
console.log(secondLine);

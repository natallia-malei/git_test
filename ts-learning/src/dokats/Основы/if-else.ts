// if...else в JavaScript/TypeScript
// Конспект по статье https://doka.guide/js/if-else/

// =============================================
// 1. Базовая форма if...else
// =============================================
// "Если условие истинно - выполнить первый блок,
// иначе - второй."

const sum = 2500;

if (sum > 2000) {
  console.log("Скидка 10%");
} else {
  console.log("Без скидки");
}

// =============================================
// 2. if без else
// =============================================
// Делаем что-то только когда условие истинно. Иначе ничего.

const isLoggedIn = true;
if (isLoggedIn) {
  console.log("Привет!");
}

// =============================================
// 3. Цепочка if...else if...else
// =============================================
// Проверяем по очереди. Срабатывает ПЕРВОЕ истинное условие,
// остальные не проверяются.

const score = 75;

if (score >= 90) {
  console.log("Отлично");
} else if (score >= 70) {
  console.log("Хорошо");
} else if (score >= 50) {
  console.log("Удовлетворительно");
} else {
  console.log("Плохо");
}

// =============================================
// 4. Что считается true и false (truthy / falsy)
// =============================================
// К false приводятся: false, 0, "", null, undefined, NaN.
// Все остальное - true.

if ("") console.log("не выполнится"); // пустая строка - falsy
if ("текст") console.log("выполнится");
if (0) console.log("не выполнится");
if (1) console.log("выполнится");

// =============================================
// 5. Операторы сравнения
// =============================================
// ===  строгое равенство (значение И тип)
// ==   нестрогое равенство (с приведением типов) - ЛУЧШЕ НЕ ИСПОЛЬЗОВАТЬ
// !==  строгое неравенство
// >, <, >=, <=  сравнения

console.log(1 === "1"); // false - разные типы
console.log(1 == "1");  // true - тут JS приводит "1" к числу
// Правило: всегда === и !==, чтобы не было сюрпризов.

// =============================================
// 6. Тернарный оператор - короткая запись if...else
// =============================================
// Условие ? значение_если_true : значение_если_false

const day = "Вторник";
const price = day === "Вторник" ? 50 : 100;
console.log(price); // 50

// Удобно когда нужно ВЫБРАТЬ значение, а не выполнить действие.

// =============================================
// 7. ?? и || - значения по умолчанию
// =============================================
// || - "первое truthy"     -> срабатывает на 0, "", false
// ?? - "первое не null/undefined" -> срабатывает ТОЛЬКО на null/undefined

const userInput1 = 0;
const value1 = userInput1 || 42;  // 42 - потому что 0 считается falsy
const value2 = userInput1 ?? 42;  // 0  - потому что 0 это не null/undefined
console.log(value1, value2);

// На практике для значений по умолчанию обычно лучше ??.

// =============================================
// 8. TS-фишка: narrowing (сужение типов)
// =============================================
// Внутри if TS понимает, какой тип у переменной, и пропускает
// то, что для этого типа разрешено. Без if - ругается.

function printLength(value: string | number) {
  // value: string | number - тут нельзя вызвать .length напрямую,
  // потому что у number нет .length.

  if (typeof value === "string") {
    // TS понял: внутри этого блока value - точно string.
    console.log(value.length); // OK
  } else {
    // А тут value - точно number.
    console.log(value.toFixed(2)); // OK
  }
}

printLength("привет"); // 6
printLength(3.14159);  // 3.14

// Это одна из самых полезных вещей в TS:
// if/else не просто управляет потоком, но и УТОЧНЯЕТ тип.

// =============================================
// 9. TS-фишка: проверка на null/undefined
// =============================================
// Если поле может быть undefined, без if к нему не подобраться.

type User = {
  name: string;
  age?: number; // age может отсутствовать
};

function describe(user: User) {
  if (user.age !== undefined) {
    console.log(`${user.name}, ${user.age} лет`);
  } else {
    console.log(`${user.name}, возраст неизвестен`);
  }
}

describe({ name: "Аня", age: 25 });
describe({ name: "Оля" });

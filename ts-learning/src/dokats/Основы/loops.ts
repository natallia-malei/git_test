// Циклы в JavaScript/TypeScript
// Конспект по статье https://doka.guide/js/loop/

// =============================================
// 1. Что такое цикл
// =============================================
// Цикл - повторение блока кода, пока условие истинно.
// Каждое повторение называется итерацией.
//
// Механизм:
//   1. проверить условие
//   2. если истинно - выполнить тело, вернуться к шагу 1
//   3. если ложно - выйти из цикла

// =============================================
// 2. while - "пока истинно"
// =============================================
// Сначала проверяет условие, потом выполняет тело.

let count: number = 10;
while (count > 0) {
  console.log(count);
  count--;
}
// 10, 9, 8, ... 1

// Главное правило: переменная в условии должна МЕНЯТЬСЯ внутри тела.
// Иначе - бесконечный цикл и зависание.

// =============================================
// 3. do...while - "выполнить, потом проверить"
// =============================================
// Тело выполняется минимум один раз - проверка происходит ПОСЛЕ.

let n: number = 0;
do {
  console.log("выполнится хотя бы раз");
  n++;
} while (n < 3);

// =============================================
// 4. for - классический цикл со счётчиком
// =============================================
// Три части в одной строке: инициализация; условие; шаг.

for (let i: number = 0; i < 5; i++) {
  console.log(i);
}
// 0, 1, 2, 3, 4

// Удобен, когда нужен ИНДЕКС (номер итерации).

// =============================================
// 5. for...of - перебор элементов массива/итерируемого
// =============================================
// Идёт по ЗНАЧЕНИЯМ - не по индексам.

const fruits: string[] = ["яблоко", "груша", "слива"];
for (const fruit of fruits) {
  // fruit имеет тип string - TS вывел его из типа массива
  console.log(fruit.toUpperCase());
}

// Это самый частый способ перебора массивов в современном TS.

// =============================================
// 6. for...in - перебор КЛЮЧЕЙ объекта (осторожно!)
// =============================================
// Идёт по именам полей. В TS у ключа ВСЕГДА тип string -
// даже если объект описан строго.

const scores = { math: 5, physics: 4, biology: 3 };

for (const subject in scores) {
  // subject: string (а не "math" | "physics" | "biology")
  // поэтому scores[subject] может вызвать ошибку TS
  console.log(subject, (scores as Record<string, number>)[subject]);
}

// На практике для перебора объекта чаще берут Object.entries():

for (const [subject, score] of Object.entries(scores)) {
  console.log(`${subject}: ${score}`);
}

// =============================================
// 7. break - выйти из цикла досрочно
// =============================================
const numbers = [1, 5, 12, 7, 3];
for (const num of numbers) {
  if (num > 10) {
    console.log("нашёл большое число:", num);
    break; // выходим, дальше не идём
  }
}

// =============================================
// 8. continue - пропустить текущую итерацию
// =============================================
for (let i = 0; i < 5; i++) {
  if (i === 2) continue; // пропускаем именно эту итерацию
  console.log(i);
}
// 0, 1, 3, 4

// Совет из статьи: break и continue усложняют чтение кода.
// Если можно перенести логику в УСЛОВИЕ цикла или внутрь if -
// делай так.

// =============================================
// 9. Методы массивов - часто ЗАМЕНА циклов
// =============================================
// В современном TS-коде вместо обычных циклов часто используют
// методы массивов. Они короче, читаемее, и лучше дружат с типами.

const ages: number[] = [10, 20, 30, 40];

// forEach - выполнить действие для каждого
ages.forEach((age) => console.log(age));

// map - получить НОВЫЙ массив с преобразованными элементами
const doubled: number[] = ages.map((age) => age * 2);
console.log(doubled); // [20, 40, 60, 80]

// filter - оставить только подходящие элементы
const adults: number[] = ages.filter((age) => age >= 18);
console.log(adults); // [20, 30, 40]

// reduce - свернуть массив в одно значение
const total: number = ages.reduce((sum, age) => sum + age, 0);
console.log(total); // 100

// Правило выбора:
// - for / for...of - нужен счётчик или сложная логика с break/continue
// - forEach        - просто что-то сделать с каждым элементом
// - map            - получить новый массив той же длины
// - filter         - оставить только нужные
// - reduce         - получить ОДНО значение из массива (сумма, max, объект)

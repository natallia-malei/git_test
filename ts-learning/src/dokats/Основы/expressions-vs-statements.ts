// Выражения (expressions) vs Инструкции (statements)
// Конспект по статье https://doka.guide/js/expressions-vs-statements/

// =============================================
// 1. Что такое выражение
// =============================================
// Выражение - это код, который ВОЗВРАЩАЕТ значение.
// Если код можно поставить справа от "=" или передать в функцию -
// это выражение.

const a = 2 + 2;              // 2 + 2  -> выражение, возвращает 4
const b = "hello".toUpperCase(); // вызов метода -> выражение, возвращает "HELLO"
const c = Math.max(1, 5, 3);  // вызов функции -> выражение, возвращает 5
const d = a > 0;              // сравнение -> выражение, возвращает boolean

console.log(a, b, c, d); // 4 "HELLO" 5 true

// Даже просто литерал - это выражение:
const justNumber = 42;        // 42 - выражение (возвращает 42)
const justString = "text";    // "text" - выражение

// =============================================
// 2. Что такое инструкция
// =============================================
// Инструкция - это команда, которая ВЫПОЛНЯЕТ действие,
// но сама по себе значение не возвращает.
// Поэтому ее нельзя присвоить переменной.

// Инструкции, которые ты уже знаешь:
// - if / else / switch       (ветвление)
// - for / while / do-while   (циклы)
// - let / const / var        (объявление переменных)
// - return                   (возврат из функции)
// - break / continue         (управление циклом)
// - throw                    (выброс ошибки)

// Пример: if это инструкция, она не возвращает значение
let result: string;
if (a > 0) {
  result = "положительное";
} else {
  result = "не положительное";
}
console.log(result);

// А такой код вызовет ошибку компиляции:
// const x = if (a > 0) { "да" } else { "нет" };   // SyntaxError!

// =============================================
// 3. Тернарный оператор - выражение!
// =============================================
// Главное отличие от if: тернарка ВОЗВРАЩАЕТ значение,
// поэтому ее можно присвоить, передать в функцию, вернуть из стрелочной.

const sign = a > 0 ? "положительное" : "не положительное";
console.log(sign);

// Это работает потому, что вся конструкция "a > 0 ? ... : ..." - выражение.

// Удобно в стрелочных функциях:
const getSign = (n: number): string => n > 0 ? "+" : n < 0 ? "-" : "0";
console.log(getSign(5));   // "+"
console.log(getSign(-3));  // "-"
console.log(getSign(0));   // "0"

// =============================================
// 4. Вызов функции - всегда выражение
// =============================================
// Даже если функция ничего не возвращает (void / undefined),
// сам вызов функции - это выражение.

const greet = (name: string): void => {
  console.log("Привет, " + name);
};

const r = greet("Наталья"); // вызов - выражение, но возвращает undefined
console.log(r);             // undefined

// Поэтому вызов функции можно ставить и как инструкцию (просто "сделай"),
// и как выражение (использовать результат).

// =============================================
// 5. Где встречаются и выражения, и инструкции
// =============================================
// Внутри инструкций часто живут выражения.

// if (ВЫРАЖЕНИЕ) { ИНСТРУКЦИИ }
const age = 20;
if (age >= 18) {            // age >= 18 - выражение (boolean)
  console.log("Взрослый");  // вызов console.log - выражение,
                            // но используется как инструкция-действие
}

// for (ИНСТРУКЦИЯ; ВЫРАЖЕНИЕ; ВЫРАЖЕНИЕ) { ... }
for (let i = 0; i < 3; i++) {
  // let i = 0  - инструкция (объявление)
  // i < 3      - выражение (сравнение)
  // i++        - выражение (инкремент, возвращает старое значение i)
  console.log(i);
}

// =============================================
// 6. Разделители: ; и ,
// =============================================
// Точка с запятой ";" разделяет ИНСТРУКЦИИ.
// Запятая "," разделяет ВЫРАЖЕНИЯ и возвращает значение последнего.

const x = (1, 2, 3);  // оператор "запятая": вычисляет все, возвращает 3
console.log(x);       // 3

// Запятая как оператор почти не используется в реальном коде,
// но важно знать, что она существует (например, в for):
for (let i = 0, j = 10; i < j; i++, j--) {
  // здесь i++, j-- - два выражения через запятую
  if (i === j) {
    console.log("встретились в", i);
    break;
  }
}

// =============================================
// 7. TS-специфика: вывод типов в выражениях
// =============================================
// TypeScript умеет вычислять тип ВЫРАЖЕНИЯ.
// Каждое выражение имеет тип, даже без явной аннотации.

const sum = 2 + 2;            // тип выводится как number
const flag = 5 > 3;           // тип выводится как boolean
const greeting = "hi" + "!";  // тип выводится как string

// Hover в VS Code покажет тип любого выражения.
// Это работает именно потому, что выражение возвращает значение,
// а у значения всегда есть тип.

// А вот у инструкции типа нет - она не возвращает значение.

// =============================================
// 8. Маленькая проверка
// =============================================
// Что из этого выражение, а что инструкция?
//
// 1. let n = 10;              -> инструкция (объявление)
// 2. n + 1                    -> выражение (возвращает 11)
// 3. n > 5                    -> выражение (boolean)
// 4. if (n > 5) {}            -> инструкция (ветвление)
// 5. n > 5 ? "да" : "нет"     -> выражение (возвращает строку)
// 6. console.log(n)           -> выражение (вызов функции)
// 7. return n;                -> инструкция (управление потоком)
// 8. n++                      -> выражение (возвращает старое n)

// Правило простое: если результат можно "поймать" в переменную - выражение.

